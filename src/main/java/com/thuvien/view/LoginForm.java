    private void lblEyeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_lblEyeMouseClicked
        // TODO add your handling code here:
        if (passWord.getEchoChar() != (char) 0) {
            passWord.setEchoChar((char) 0);    // Hiện rõ mật khẩu
            lblEye.setText("👁");              // Đổi sang mắt mở
        } else {
            // Đang mở -> CHE LẠI
            passWord.setEchoChar('•');         // Che lại thành dấu chấm
            lblEye.setText("Ø");               // Đổi lại thành mắt gạch chéo ban đầu
        }
    }//GEN-LAST:event_lblEyeMouseClicked

    private void Forgot_PasswordMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_Forgot_PasswordMouseClicked
        // TODO add your handling code here:
        if (!rdoDocGia.isSelected()) {
            JOptionPane.showMessageDialog(this,
                "Chức năng này chỉ dành cho Độc giả!");
            return;
        }
        
        // Thông báo khi bấm quên mật khẩu
        String user = JOptionPane.showInputDialog(this, "Nhập tên đăng nhập của bạn:");

        if (user != null && !user.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng liên hệ Admin để cấp lại mật khẩu cho tài khoản: " + user.trim());
        }
    }//GEN-LAST:event_Forgot_PasswordMouseClicked

    private void SignInActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SignInActionPerformed
        // TODO add your handling code here:
        String user = userName.getText().trim();
        String pass = new String(passWord.getPassword());
        String role = rdoAdmin.isSelected() ? "ADMIN"
                    : rdoDocGia.isSelected() ? "DOCGIA" : null;   // null = chưa chọn

        // Controller trả về null nếu thành công, ngược lại trả về nội dung lỗi 
        //2. KHẮC PHỤC LỖI: khởi tạo DangNhapController để gọi hmf login
        DangNhapController controller = new DangNhapController();
        String loi = controller.login(user, pass, role);
//        String loi = new PhienDangNhap().login(user, pass, role);
        if (loi != null) {
            JOptionPane.showMessageDialog(this, loi);
            passWord.setText("");
            passWord.requestFocus();
            return;
        }

        // ===== Ghi nhớ đăng nhập (chỉ chạy khi đăng nhập đúng) =====
        java.util.prefs.Preferences prefs =
                java.util.prefs.Preferences.userRoot().node("thuvien/login");
        if (checkRememberMe.isSelected()) {
            prefs.put("username", user);
        } else {
            prefs.remove("username");
        }
        // ===========================================================

        // Vào thẳng giao diện, không popup
        if (PhienDangNhap.isAdmin()) {
            new MainAdminFrame2().setVisible(true);
        } /*else {
            new GiaoDienDocGia().setVisible(true);   // bỏ comment khi có form độc giả
            System.out.println("Đăng nhập độc giả: " + PhienDangNhap.tenDocGia);   // chỉ để thử
        }*/
        this.dispose();
    }//GEN-LAST:event_SignInActionPerformed

    
    
    

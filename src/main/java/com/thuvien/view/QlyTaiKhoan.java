    private void taiLaiBang() {
        DefaultTableModel model = (DefaultTableModel) tblTaiKhoan.getModel();
        model.setRowCount(0);
        try {
            int stt = 1;
            for (Object[] r : controller.layDanhSach()) {
              model.addRow(new Object[]{stt++, r[0], r[1], r[2], r[3], r[4] == null ? "" : r[4]});
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Không tải được dữ liệu: " + ex.getMessage());
        }
    }
    
    
    private String layMaDangChon() {
        int dong = tblTaiKhoan.getSelectedRow();
        if (dong < 0) return null;
        dong = tblTaiKhoan.convertRowIndexToModel(dong);
        return String.valueOf(tblTaiKhoan.getModel().getValueAt(dong, 1));   // cột Mã TK
    }
    
    

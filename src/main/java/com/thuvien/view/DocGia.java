    // Bỏ dấu tiếng Việt và đổi về chữ thường để so sánh
    private String boDau(String s) {
        String khongDau = Normalizer.normalize(s, Normalizer.Form.NFD)
                .replaceAll("\\p{M}", "")
                .replace('đ', 'd').replace('Đ', 'D');
        return khongDau.toLowerCase();
    }


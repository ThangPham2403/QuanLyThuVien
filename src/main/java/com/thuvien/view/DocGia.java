    // Hiện màn hình đã thêm sẵn trong constructor, và tô xanh mục đang chọn
    private void chuyenManHinh(String cardName, JButton nutDangChon) {
        ((java.awt.CardLayout) pnlNoiDung.getLayout()).show(pnlNoiDung, cardName);

        for (JButton nut : cacNut) {                       // trả các mục về dạng thường
            nut.setBackground(java.awt.Color.WHITE);
            nut.setForeground(java.awt.Color.BLACK);
        }
        if (nutDangChon != null) {                         // mục đang chọn: nền xanh
            nutDangChon.setBackground(new java.awt.Color(0, 153, 0));
            nutDangChon.setForeground(java.awt.Color.WHITE);
        }
    }

    // Tạo panel MỚI mỗi lần bấm, để dữ liệu luôn được tải lại
    private void moManHinhMoi(String cardName, javax.swing.JPanel panel, JButton nutDangChon) {
        for (java.awt.Component c : pnlNoiDung.getComponents()) {   // bỏ bản cũ cùng tên nếu có
            if (cardName.equals(c.getName())) {
                pnlNoiDung.remove(c);
                break;
            }
        }
        panel.setName(cardName);
        pnlNoiDung.add(panel, cardName);
        chuyenManHinh(cardName, nutDangChon);
    }
    
